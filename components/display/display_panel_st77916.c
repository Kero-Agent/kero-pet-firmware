typedef struct {
    const char *name;
    const st77916_lcd_init_cmd_t *cmds;     /* NULL: the component's own sequence */
    uint16_t count;
} variant_t;

#define TABLE(t) (t), sizeof(t) / sizeof((t)[0])

static const variant_t s_variants[] = {
    { "esp_lcd_st77916 default", NULL, 0 },
    { "JC3636W518", TABLE(init_jc3636w518) },
    { "JC3636W518 V2", TABLE(init_jc3636w518_v2) },
};
static int s_variant = 2;      /* confirmed on the WLK1804RCTP-14P: 0 and 1 give no picture */

int display_panel_variant_count(void)
{
    return sizeof(s_variants) / sizeof(s_variants[0]);
}

const char *display_panel_variant_name(int index)
{
    return (index >= 0 && index < display_panel_variant_count()) ? s_variants[index].name : "?";
}

int display_panel_get_variant(void)
{
    return s_variant;
}

void display_panel_set_variant(int index)
{
    if (index >= 0 && index < display_panel_variant_count()) {
        s_variant = index;
    }
}

const char *display_panel_name(void)
{
    return "ST77916";
}

void display_panel_get_io_params(display_panel_io_params_t *out)
{
    out->lcd_cmd_bits = 32;     /* QSPI: 0x02 / 0x32 opcode + 24-bit address carrying the command */
    out->lcd_param_bits = 8;
    out->spi_mode = 0;
}

esp_err_t display_panel_create(esp_lcd_panel_io_handle_t io, esp_lcd_panel_handle_t *out_panel)
{
    /* static: the driver keeps the pointers for as long as the panel exists */
    static st77916_vendor_config_t vendor;
    vendor = (st77916_vendor_config_t) {
        .init_cmds = s_variants[s_variant].cmds,
        .init_cmds_size = s_variants[s_variant].count,
        .flags = {
            .use_qspi_interface = 1,
        },
    };
    const esp_lcd_panel_dev_config_t cfg = {
        .reset_gpio_num = -1,       /* not wired: the driver sends a software reset */
        .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 16,
        .vendor_config = &vendor,
    };
    return esp_lcd_new_panel_st77916(io, &cfg, out_panel);
}
